        public static string GetComboName(int combo, int language)
        {
            Dictionary<int, string> targetLanguage = new Dictionary<int, string>();
            switch (language)
            {
                case 0: targetLanguage = en; break;
                case 1: targetLanguage = ja; break;
                case 2: targetLanguage = zh_cn; break;
                case 3: targetLanguage = zh_tw; break;
            }
            if (targetLanguage.TryGetValue(combo, out string? value))
            {
                return value;
            }
            else
            {
                return "(null)";
            }
        }
